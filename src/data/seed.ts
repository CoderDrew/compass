export function createSeedData(now: Date = new Date()): AppData {
  const iso = now.toISOString();
  let n = 0;
  const nid = (p: string) => `${p}-seed-${++n}`;
  const projects: Project[] = SEED.map((s) => ({
    ...s,
    relatedIds: s.relatedIds ?? [],
    blockers: s.blockers ?? '',
    waitingOn: s.waitingOn ?? '',
    notes: s.notes ?? '',
    tasks: (s.tasks ?? []).map((t) => ({ ...t, id: nid('t') })),
    milestones: (s.milestones ?? []).map((m) => ({ ...m, id: nid('m') })),
    lastActivity: iso,
    createdAt: iso,
    updatedAt: iso,
  }));

  return {
    schemaVersion: SCHEMA_VERSION,
    projects,
    activity: [{ id: nid('a'), at: iso, kind: 'project', text: 'Portfolio seeded with initial snapshot' }],
    journal: [],
    weeks: {},
    allocations: [
      { id: 'alloc-employment', label: 'Day job — regular employment hours', projectIds: ['day-job'], blocks: 1, kind: 'fixed', protected: true },
      { id: 'alloc-client', label: 'Client delivery', projectIds: ['harbor-web', 'mindjax'], blocks: 2, kind: 'focus' },
      { id: 'alloc-convention', label: 'Convention preparation', projectIds: ['lighthouse', 'promo-kit'], blocks: 1, kind: 'focus' },
      { id: 'alloc-creative', label: 'Starfall — protected creative block', projectIds: ['starfall'], blocks: 1, kind: 'focus' },
      { id: 'alloc-rotating', label: 'Rotating: Tablebook, RPG tools, or skills', projectIds: ['tablebook', 'rpg-tools', 'skills-dev'], blocks: 1, kind: 'focus' },
      { id: 'alloc-review', label: 'Weekly portfolio review', projectIds: [], blocks: 1, kind: 'recurring', hours: 0.25 },
    ],
    settings: { theme: 'dark', weeklyCapacity: 12, employmentHours: 40, blockHours: 2 },
    seededAt: iso,
  };
}
