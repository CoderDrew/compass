export function createSeedData(now: Date = new Date()): AppData {
  const iso = now.toISOString();
  let n = 0;
  const nid = (p: string) => `${p}-seed-${++n}`;
  const projects: Project[] = SEED.map((s) => ({
    ...s,
    relatedIds: s.relatedIds ?? [],
    blockers: s.blockers ?? '',
    waitingOn: s.waitingOn ?? '',
    notes: s.notes ?? '',
    tasks: (s.tasks ?? []).map((t) => ({ ...t, id: nid('t') })),
    milestones: (s.milestones ?? []).map((m) => ({ ...m, id: nid('m') })),
    lastActivity: iso,
    createdAt: iso,
    updatedAt: iso,
  }));

  return {
    schemaVersion: SCHEMA_VERSION,
    projects,
    activity: [{ id: nid('a'), at: iso, kind: 'project', text: 'Portfolio seeded with initial snapshot' }],
    weeks: {},
    allocations: [
      { id: 'alloc-antech', label: 'Antech — regular employment hours', projectIds: ['antech'], blocks: 1, kind: 'fixed', protected: true },
      { id: 'alloc-client', label: 'Olympus / Mindjax client delivery', projectIds: ['olympus-web', 'mindjax'], blocks: 2, kind: 'focus' },
      { id: 'alloc-convention', label: 'Ravenloft / convention preparation', projectIds: ['ravenloft', 'hazard-quest'], blocks: 1, kind: 'focus' },
      { id: 'alloc-voidraider', label: 'Voidraider — protected creative block', projectIds: ['voidraider'], blocks: 1, kind: 'focus' },
      { id: 'alloc-rotating', label: 'Rotating: OneShotz, DCC, or AI career', projectIds: ['oneshotz', 'dcc-tools', 'ai-career-dev'], blocks: 1, kind: 'focus' },
      { id: 'alloc-review', label: 'Weekly portfolio review', projectIds: [], blocks: 1, kind: 'recurring', hours: 0.25 },
    ],
    settings: { theme: 'dark', weeklyCapacity: 12, employmentHours: 40, blockHours: 2 },
    seededAt: iso,
  };
}
